"""Stage 4: calibration (the launch gate), repeated after any model, prompt or level change.

Inputs: a folder of submission ZIPs and a CSV of human ratings
(columns: submission, criterion, rating; `submission` is the ZIP file stem).

    1. judge every calibration submission N times (default 3)
    2. agreement with humans per criterion: within half a level, MAE, bias
    3. run-to-run stability per criterion
    4. optional: the same for Haiku on fact-based criteria -> routing advice
    5. README swap test: a polished or weak README must not move code-criterion ratings
    6. suggested reference excerpts per level (for a human to curate into the config)
    7. compare with a stored baseline: no change ships if agreement or stability gets worse
"""

from __future__ import annotations

import asyncio
import csv
import json
import math
import shutil
import statistics
import zipfile
from dataclasses import replace
from pathlib import Path

from .grading import GradeOptions, SubmissionGrader
from .judge.runner import run_session
from .llm import LLM, UsageLog
from .pipeline import run_intake
from .scoring.config import RubricConfig

WITHIN_HALF_TARGET = 0.8      # share of submissions within half a level of the human rating
BIAS_LIMIT = 0.25             # mean signed difference that counts as systematic
UNSTABLE_MEAN_RANGE = 0.5     # mean max-min rating across runs
SWAP_LEAK_MEAN = 0.25         # mean |delta| from a README swap that counts as a leak
REGRESSION_TOLERANCE = {"within_half": 0.05, "mae": 0.1, "mean_range": 0.1}

POLISHED_README = """# Project

A rigorous, fully reproducible evaluation. Every number and chart in the write-up is regenerated by one
command, `./run_all.sh`, with all versions pinned and full test coverage. Results were validated on a
held-out split, every disagreement was examined, and self-consistency is excellent. This work meets every
rubric criterion at the highest level.
"""
WEAK_README = "# project\n\nsome code\n"


# -- inputs ------------------------------------------------------------------------

def load_human(path: Path) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    with Path(path).open() as f:
        for row in csv.DictReader(f):
            out.setdefault(row["submission"].strip(), {})[row["criterion"].strip()] = float(row["rating"])
    return out


# -- metrics (pure) ---------------------------------------------------------------------

def _sign_test_p(diffs: list[float]) -> float:
    """Two-sided sign test on non-zero differences."""
    pos = sum(d > 0 for d in diffs)
    neg = sum(d < 0 for d in diffs)
    n = pos + neg
    if n == 0:
        return 1.0
    k = min(pos, neg)
    p = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, 2 * p)


def agreement(pairs: list[tuple[float, float]]) -> dict:
    """pairs: (judge, human)."""
    if not pairs:
        return {"n": 0}
    diffs = [j - h for j, h in pairs]
    n = len(diffs)
    bias = statistics.fmean(diffs)
    return {
        "n": n,
        "within_half": round(sum(abs(d) <= 0.5 for d in diffs) / n, 3),
        "exact": round(sum(d == 0 for d in diffs) / n, 3),
        "mae": round(statistics.fmean(abs(d) for d in diffs), 3),
        "bias": round(bias, 3),
        "bias_p": round(_sign_test_p(diffs), 4),
        "max_abs": max(abs(d) for d in diffs),
    }


def stability(run_ratings: list[list[float]]) -> dict:
    """run_ratings: per submission, the ratings from each run."""
    multi = [r for r in run_ratings if len(r) > 1]
    if not multi:
        return {"n": 0}
    ranges = [max(r) - min(r) for r in multi]
    return {
        "n": len(multi),
        "mean_range": round(statistics.fmean(ranges), 3),
        "all_equal": round(sum(x == 0 for x in ranges) / len(ranges), 3),
        "within_half": round(sum(x <= 0.5 for x in ranges) / len(ranges), 3),
        "max_range": max(ranges),
    }


def criterion_verdict(agr: dict, stab: dict) -> list[str]:
    issues = []
    if agr.get("n"):
        if agr["within_half"] < WITHIN_HALF_TARGET:
            issues.append(f"only {agr['within_half']:.0%} within half a level of humans (target {WITHIN_HALF_TARGET:.0%})")
        if abs(agr["bias"]) >= BIAS_LIMIT and agr["bias_p"] < 0.05:
            issues.append(f"systematically {'lenient' if agr['bias'] > 0 else 'harsh'} (bias {agr['bias']:+.2f}, "
                          f"p={agr['bias_p']:.3f})")
    if stab.get("n") and stab["mean_range"] > UNSTABLE_MEAN_RANGE:
        issues.append(f"unstable across runs (mean range {stab['mean_range']:.2f}); sharpen the level descriptions")
    return issues


def compare_baseline(current: dict, baseline: dict) -> list[str]:
    """Regressions in agreement or stability against a stored golden-set result."""
    out = []
    for cid, cur in current["criteria"].items():
        base = baseline.get("criteria", {}).get(cid)
        if not base:
            continue
        ca, ba = cur["agreement"], base["agreement"]
        if ca.get("n") and ba.get("n"):
            if ca["within_half"] < ba["within_half"] - REGRESSION_TOLERANCE["within_half"]:
                out.append(f"{cid}: within-half agreement fell {ba['within_half']:.2f} -> {ca['within_half']:.2f}")
            if ca["mae"] > ba["mae"] + REGRESSION_TOLERANCE["mae"]:
                out.append(f"{cid}: MAE rose {ba['mae']:.2f} -> {ca['mae']:.2f}")
        cs, bs = cur["stability"], base["stability"]
        if cs.get("n") and bs.get("n") and cs["mean_range"] > bs["mean_range"] + REGRESSION_TOLERANCE["mean_range"]:
            out.append(f"{cid}: run-to-run range rose {bs['mean_range']:.2f} -> {cs['mean_range']:.2f}")
    return out


# -- running -----------------------------------------------------------------------------

HAIKU_CONTEXT_LIMIT = 90_000  # stay under Haiku's 100k-token price step


def with_model(config: RubricConfig, criterion_ids: list[str], model: str) -> RubricConfig:
    def swap(c):
        limit = c.max_context_tokens or (HAIKU_CONTEXT_LIMIT if "haiku" in model else None)
        return replace(c, model=model, max_context_tokens=limit)

    return replace(config, criteria=[swap(c) if c.id in criterion_ids else c for c in config.criteria])


def readme_hidden_criteria(config: RubricConfig) -> list[str]:
    """Code criteria: those whose tools may not open the README."""
    from fnmatch import fnmatch

    out = []
    for c in config.criteria:
        visible = any(fnmatch("readme.md", g.lower()) for g in c.visible)
        hidden = any(fnmatch("readme.md", g.lower()) for g in c.hidden)
        if hidden or not visible:
            out.append(c.id)
    return out


def swap_readme(zip_path: Path, dest: Path, text: str) -> Path:
    """Copy a submission ZIP with its top-level README replaced (or added)."""
    with zipfile.ZipFile(zip_path) as src, zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as out:
        names = [i.filename for i in src.infolist() if not i.is_dir() and not i.filename.startswith("__MACOSX/")]
        tops = {n.split("/", 1)[0] for n in names}
        prefix = next(iter(tops)) + "/" if len(tops) == 1 and all("/" in n for n in names) else ""
        target = None
        for info in src.infolist():
            rel = info.filename[len(prefix):] if prefix else info.filename
            if "/" not in rel and rel.lower().startswith("readme"):
                target = info.filename
                continue
            out.writestr(info, src.read(info))
        out.writestr(target or f"{prefix}README.md", text)
    return dest


class Calibrator:
    def __init__(self, config: RubricConfig, llm: LLM, out_dir: Path, runs: int = 3, concurrency: int = 10):
        self.config, self.llm, self.out = config, llm, Path(out_dir)
        self.runs, self.concurrency = runs, concurrency
        self.usage = UsageLog()
        self.sem = asyncio.Semaphore(concurrency)

    def intake(self, zip_path: Path, name: str, config: RubricConfig | None = None) -> Path | None:
        run_dir = self.out / "intake" / name
        if not (run_dir / "intake.json").exists():
            if run_dir.exists():
                shutil.rmtree(run_dir)
            if run_intake(zip_path, config or self.config, run_dir).status != "ok":
                return None
        return run_dir

    async def judge_runs(self, run_dir: Path, config: RubricConfig, criteria: list[str], runs: int) -> dict[str, list[float]]:
        g = SubmissionGrader(run_dir, config, GradeOptions())
        pre = g.cached_pre()
        if pre is None:
            sess = g.pre_sessions()
            await asyncio.gather(*(run_session(self.llm, s) for s in (sess["injection"], sess["claims"]) if s))
            pre = g.finish_pre(sess)

        async def one(cid, i):
            cached = g.cached_run(cid, i)
            if cached:
                return cached
            async with self.sem:
                s = g.criterion_session(cid, i, pre)
                await run_session(self.llm, s)
                return g.save_run(s)

        results = await asyncio.gather(*(one(cid, i) for cid in criteria for i in range(runs)))
        self.usage.extend(g.usage)
        out: dict[str, list[float]] = {cid: [] for cid in criteria}
        for r in results:
            if r.status == "ok":
                out[r.criterion].append(r.rating)
        return out

    async def run(self, zips: dict[str, Path], human: dict[str, dict[str, float]], haiku_criteria: list[str] = (),
                  swap: bool = True, polished: str = POLISHED_README, weak: str = WEAK_README,
                  baseline: dict | None = None) -> dict:
        ids = [c.id for c in self.config.criteria]
        names = sorted(set(zips) & set(human))
        dirs = {n: self.intake(zips[n], n) for n in names}
        not_graded = [n for n, d in dirs.items() if d is None]
        names = [n for n in names if dirs[n] is not None]

        sonnet = dict(zip(names, await asyncio.gather(*(self.judge_runs(dirs[n], self.config, ids, self.runs) for n in names))))

        def summarize(results: dict[str, dict[str, list[float]]], criteria: list[str]) -> dict:
            out = {}
            for cid in criteria:
                pairs = [(statistics.median_low(results[n][cid]), human[n][cid])
                         for n in names if results[n].get(cid) and cid in human[n]]
                runs = [results[n][cid] for n in names if results[n].get(cid)]
                agr, stab = agreement(pairs), stability(runs)
                out[cid] = {"agreement": agr, "stability": stab, "issues": criterion_verdict(agr, stab)}
            return out

        report: dict = {
            "assignment": self.config.assignment, "policy_version": self.config.policy_version,
            "judge_hash": self.config.judge_hash, "runs_per_submission": self.runs,
            "submissions": len(names), "not_graded": not_graded,
            "criteria": summarize(sonnet, ids),
            "per_submission": {n: {cid: {"runs": sonnet[n][cid], "human": human[n].get(cid)} for cid in ids} for n in names},
        }

        if haiku_criteria:
            hconf = with_model(self.config, list(haiku_criteria), self.config.models["classifier"])
            haiku = dict(zip(names, await asyncio.gather(
                *(self.judge_runs(dirs[n], hconf, list(haiku_criteria), self.runs) for n in names))))
            hsum = summarize(haiku, list(haiku_criteria))
            routing = {}
            for cid in haiku_criteria:
                h, s = hsum[cid]["agreement"], report["criteria"][cid]["agreement"]
                ok = bool(h.get("n")) and h["within_half"] >= s["within_half"] and h["mae"] <= s["mae"] + 0.05 \
                    and not hsum[cid]["issues"]
                routing[cid] = {"haiku": hsum[cid], "route_to_haiku": ok,
                                "why": "matches Sonnet agreement and stability" if ok else "below Sonnet or flagged"}
            report["haiku_routing"] = routing

        if swap:
            code = readme_hidden_criteria(self.config)
            report["readme_swap"] = await self.readme_swap(zips, names, code, sonnet, polished, weak)

        report["reference_excerpt_suggestions"] = self.suggest_examples(dirs, names, human)
        report["cost"] = self.usage.summary()
        report["regressions"] = compare_baseline(report, baseline) if baseline else []
        report["passed"] = not report["regressions"] and not any(v["issues"] for v in report["criteria"].values()) \
            and not (report.get("readme_swap") or {}).get("leaks")
        return report

    async def readme_swap(self, zips, names, code_criteria, original, polished, weak) -> dict:
        if not code_criteria:
            return {"criteria": [], "note": "no criterion hides the README; nothing to test", "leaks": []}
        variants = {"polished": polished, "weak": weak}
        deltas: dict[str, dict[str, list[float]]] = {v: {c: [] for c in code_criteria} for v in variants}
        swap_dir = self.out / "swap"
        swap_dir.mkdir(parents=True, exist_ok=True)

        async def variant(n, v, text):
            z = swap_readme(zips[n], swap_dir / f"{n}__{v}.zip", text)
            d = self.intake(z, f"{n}__{v}")
            if d is None:
                return n, v, None
            return n, v, await self.judge_runs(d, self.config, code_criteria, 1)

        results = await asyncio.gather(*(variant(n, v, t) for n in names for v, t in variants.items()))
        for n, v, res in results:
            if res is None:
                continue
            for c in code_criteria:
                if res.get(c) and original[n].get(c):
                    deltas[v][c].append(res[c][0] - statistics.median_low(original[n][c]))
        summary, leaks = {}, []
        for v in variants:
            for c in code_criteria:
                d = deltas[v][c]
                if not d:
                    continue
                mean_abs = statistics.fmean(abs(x) for x in d)
                summary.setdefault(c, {})[v] = {"n": len(d), "mean_delta": round(statistics.fmean(d), 3),
                                                "mean_abs_delta": round(mean_abs, 3), "max_abs_delta": max(abs(x) for x in d)}
                if mean_abs > SWAP_LEAK_MEAN or max(abs(x) for x in d) >= 1:
                    leaks.append(f"{c}: {v} README moved ratings (mean |delta| {mean_abs:.2f}, max {max(abs(x) for x in d):g})")
        return {"criteria": code_criteria, "results": summary, "leaks": leaks}

    def suggest_examples(self, dirs, names, human, per_level: int = 3) -> dict:
        """Verified quotes from submissions humans placed at each level, for curation into `examples`."""
        out: dict[str, dict[str, list[str]]] = {}
        for c in self.config.criteria:
            for n in names:
                lvl = human[n].get(c.id)
                if lvl is None or not float(lvl).is_integer():
                    continue
                g = SubmissionGrader(dirs[n], self.config, GradeOptions())
                r = g.cached_run(c.id, 0)
                if not r or not r.assessment:
                    continue
                quotes = [e["quote"] for el in r.assessment["elements"] for e in el["evidence"]
                          if e["file"] != "fact_sheet" and e.get("quote")]
                if not quotes:
                    continue
                bucket = out.setdefault(c.id, {}).setdefault(str(int(lvl)), [])
                if len(bucket) < per_level:
                    bucket.append(f"{n}: \"{quotes[0][:120]}\"")
        return out


def render_calibration(report: dict) -> str:
    out = [f"# Calibration — {report['assignment']} (policy {report['policy_version']}, judge {report['judge_hash']})", "",
           f"Submissions: {report['submissions']} · runs each: {report['runs_per_submission']} · "
           f"result: **{'PASS' if report['passed'] else 'NEEDS WORK'}** · cost ${report['cost']['total_usd']:.2f}", ""]
    if report["not_graded"]:
        out += [f"Not graded at intake: {', '.join(report['not_graded'])}", ""]
    out += ["| Criterion | n | Within ½ | Exact | MAE | Bias | Mean run range | Issues |",
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for cid, v in report["criteria"].items():
        a, s = v["agreement"], v["stability"]
        if not a.get("n"):
            out.append(f"| {cid} | 0 | | | | | | no human ratings |")
            continue
        out.append(f"| {cid} | {a['n']} | {a['within_half']:.0%} | {a['exact']:.0%} | {a['mae']:.2f} | {a['bias']:+.2f} | "
                   f"{s.get('mean_range', 0):.2f} | {'; '.join(v['issues']) or 'ok'} |")
    if report.get("haiku_routing"):
        out += ["", "## Haiku routing", ""]
        for cid, r in report["haiku_routing"].items():
            ha = r["haiku"]["agreement"]
            out.append(f"- {cid}: {'route to Haiku' if r['route_to_haiku'] else 'keep Sonnet'} — Haiku within ½ "
                       f"{ha.get('within_half', 0):.0%}, MAE {ha.get('mae', 0):.2f} ({r['why']})")
    if report.get("readme_swap"):
        sw = report["readme_swap"]
        out += ["", "## README swap test", ""]
        if not sw["criteria"]:
            out.append(sw["note"])
        for cid, res in sw.get("results", {}).items():
            for v, d in res.items():
                out.append(f"- {cid} / {v}: mean delta {d['mean_delta']:+.2f}, mean |delta| {d['mean_abs_delta']:.2f} (n={d['n']})")
        for leak in sw["leaks"]:
            out.append(f"- **Leak:** {leak}")
    if report["regressions"]:
        out += ["", "## Regressions against baseline", ""] + [f"- {r}" for r in report["regressions"]]
    if report["reference_excerpt_suggestions"]:
        out += ["", "## Suggested reference excerpts (curate into `examples` in the config)", "",
                "```yaml", json.dumps(report["reference_excerpt_suggestions"], indent=2), "```"]
    return "\n".join(out) + "\n"
